def sources_for_page(page_id: DashboardPageId | str) -> tuple[DashboardSourceContract, ...]:
    page = page_id if isinstance(page_id, DashboardPageId) else DashboardPageId(page_id)
    return SOURCE_CATALOG[page]


def iter_sources() -> Iterable[DashboardSourceContract]:
    for page_id in DashboardPageId:
        yield from SOURCE_CATALOG[page_id]


def snapshot_path_for_page(page_id: DashboardPageId | str) -> str:
    page = page_id if isinstance(page_id, DashboardPageId) else DashboardPageId(page_id)
    return f"data/reports/{DASHBOARD_SNAPSHOT_FILENAMES[page]}"
