def _source(
    page_id: DashboardPageId,
    path: str,
    source_kind: SourceKind = SourceKind.OPTIONAL_EXISTING_SOURCE,
    description: str = "",
) -> DashboardSourceContract:
    return DashboardSourceContract(page_id, path, source_kind, description)


def _generated(page_id: DashboardPageId) -> DashboardSourceContract:
    filename = DASHBOARD_SNAPSHOT_FILENAMES[page_id]
    return _source(
        page_id,
        f"data/reports/{filename}",
        SourceKind.GENERATED_BY_THIS_BRANCH,
        "Read-only dashboard snapshot generated by the dashboard snapshot family.",
    )


